// The Markdown report written beside the JSON results.
import type { CellSummary, Results } from "./run";

const pct = (x: number) => `${Math.round(x * 100)}%`;
const kb = (b: number) => (b >= 1024 ? `${(b / 1024).toFixed(1)} kB` : `${Math.round(b)} B`);

function successCell(c: CellSummary): string {
  return `${c.successes}/${c.runs} (${pct(c.wilson95.low)}–${pct(c.wilson95.high)})`;
}

export const CAVEATS = [
  "Scripted, not model-driven. Each variant is driven by a deterministic program that does the best it can with what the variant exposes. Success here is not evidence of how a model-driven agent performs; a model can misread a page, pick the wrong tool, or ignore a reason that the script always handles.",
  "Deterministic by construction. Repeated runs differ only in timing; the confidence intervals are Wilson intervals over n runs and mostly reflect how few runs there are, not behavioral variance.",
  'Tokens are not measured: no model runs. "Agent bytes" is what the scripted program read and sent (MCP messages for v3 and v4; one accessibility snapshot per observation for v1 and v2). It is a size, not a token count, and the two kinds of bytes are not equivalent inputs to a model.',
  "Latency is wall time on one machine against a local production build, excluding sign-in or MCP connect. Browser variants include rendering, the page's 1.5-second polling, and Playwright waits; the lost-response case includes the policy's 4-second wait for an outcome.",
  "One application, written by the same team that wrote the SDK, with tasks chosen to exercise the faults the SDK was designed for. The v3 wrapper is deliberately thin; a careful team could add a revision check to it, and would then be building part of v4.",
  "The app locks whole plans, not months, so the unavailable-control scenario uses a submitted plan.",
  "The UI change renames only the Save button's visible text. The Surface entry's name, which v2's accessible name comes from, is left as it was, as it would be for a cosmetic rename; renaming the entry too would break v2 the same way it breaks v1. The v1 script maps columns by their header text, which is why moving the item column breaks nothing on its own; a script that clicked by raw position would break there too.",
  "The reference page does not recover from a failed save request: the Save button stays disabled until the page reloads. The browser scripts reload after waiting; a model-driven agent might not.",
  "The person beside the agent is scripted: their edits use the page's own endpoints at the revision they just loaded, and an approval is one request.",
];

export function renderMarkdown(r: Results): string {
  const lines: string[] = [];
  const L = (s = "") => lines.push(s);
  L(`# Evaluation run, ${r.date}`);
  L();
  L(`> **${r.disclaimer}**`);
  L();
  L(
    "Generated by `pnpm eval` (examples/plan-review/eval/run.ts). The JSON beside this file has every run.",
  );
  L();
  L("## Environment");
  L();
  L("| Key | Value |");
  L("| --- | --- |");
  for (const [k, v] of Object.entries(r.environment)) L(`| ${k} | ${String(v)} |`);
  L(`| runs per cell | ${r.config.runs} |`);
  L(`| runs per cell after the UI change | ${r.config.maintenanceRuns} |`);
  L();
  L("## Variants");
  L();
  L("| Variant | How the scripted agent works | Integration lines |");
  L("| --- | --- | --- |");
  for (const v of r.variants) {
    const i = r.integration.find((x) => x.variant === v.id);
    L(`| ${v.title} | ${v.how} | ${i ? `${i.lines} (${i.note})` : ""} |`);
  }
  L();
  L(
    "Setup before each task, not counted in the measures below: signing in and loading the plan page (v1, v2), or connecting to the MCP server and listing its tools (v3, v4; v4 also fetches the manifest). Medians over every run.",
  );
  L();
  L("| Variant | Setup requests | Setup bytes |");
  L("| --- | --- | --- |");
  for (const v of r.variants) {
    const cs = r.summary.filter((c) => c.variant === v.id);
    if (!cs.length) continue;
    const med = (xs: number[]) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)] ?? 0;
    L(
      `| ${v.id} | ${med(cs.map((c) => c.medianSetupRequests))} | ${kb(med(cs.map((c) => c.medianSetupBytes)))} |`,
    );
  }
  L();
  L("## Scenarios");
  L();
  L("| Scenario | Task | Fault |");
  L("| --- | --- | --- |");
  for (const s of r.scenarios) L(`| ${s.title} | ${s.task} | ${s.fault} |`);
  L();
  L("## Success by scenario and variant");
  L();
  L(
    "Successes over runs, with a 95% Wilson interval. A success means the application's final state and history match the task, with no incorrect agent write, and (for the unavailable control) the agent relayed the app's own reason.",
  );
  L();
  L(`| Scenario | ${r.variants.map((v) => v.id).join(" | ")} |`);
  L(`| --- | ${r.variants.map(() => "---").join(" | ")} |`);
  for (const s of r.scenarios) {
    const cells = r.variants.map((v) => {
      const c = r.summary.find((x) => x.variant === v.id && x.scenario === s.id);
      if (!c) return "";
      return `${successCell(c)}${c.faultApplies ? "" : " ¹"}`;
    });
    L(`| ${s.title} | ${cells.join(" | ")} |`);
  }
  L();
  L(
    "¹ The fault does not exist for this variant (server tools have no page to navigate away from).",
  );
  L();
  L("## All measures");
  L();
  L(
    "Medians over runs, except incorrect mutations (total over runs) and recovered (runs). Tokens: n/a for every row (no model).",
  );
  L();
  L(
    "| Scenario | Variant | Success | Incorrect mutations | Recovered | Human interventions | Write attempts | Conflicts | Refusals | Completed by | HTTP requests | HTTP bytes | Agent bytes | Latency ms, median (max) |",
  );
  L("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const s of r.scenarios)
    for (const v of r.variants) {
      const c = r.summary.find((x) => x.variant === v.id && x.scenario === s.id);
      if (!c) continue;
      L(
        `| ${s.title} | ${v.id} | ${successCell(c)} | ${c.incorrectMutations} | ${c.recovered} | ${c.interventions} | ${c.writeAttempts} | ${c.conflicts} | ${c.refusals} | ${c.completedBy} | ${c.medianHttpRequests} | ${kb(c.medianHttpBytes)} | ${kb(c.medianAgentBytes)} | ${Math.round(c.medianLatencyMs)} (${c.maxLatencyMs}) |`,
      );
    }
  L();
  const failures = r.summary.filter((c) => c.successes < c.runs);
  if (failures.length) {
    L("### Why the failures failed");
    L();
    for (const c of failures)
      L(
        `- ${c.scenario}, ${c.variant}: ${[...c.mismatches, ...c.errors].join("; ") || "the reason the agent relayed was not the app's reason"}`,
      );
    L();
  }
  L("## Maintenance after a controlled UI change");
  L();
  L(
    'The server was restarted with `PLAN_REVIEW_UI_CHANGE=1`: the Save button\'s visible label becomes "Apply changes" and the item column moves to the end of each row. The scripted agents ran again without any change to their code. A scenario counts as broken when it succeeded in every run before the change and failed in any run after it.',
  );
  L();
  L("| Variant | Broken scenarios | Which |");
  L("| --- | --- | --- |");
  for (const v of r.variants) {
    const broken = r.scenarios.filter((s) => {
      const before = r.summary.find((x) => x.variant === v.id && x.scenario === s.id);
      const after = r.maintenanceSummary.find((x) => x.variant === v.id && x.scenario === s.id);
      return before && after && before.successes === before.runs && after.successes < after.runs;
    });
    const ran = r.maintenanceSummary.some((x) => x.variant === v.id);
    L(
      `| ${v.id} | ${ran ? `${broken.length} of ${r.scenarios.length}` : "not run"} | ${broken.map((s) => s.id).join(", ") || "none"} |`,
    );
  }
  L();
  L("## Caveats");
  L();
  for (const c of CAVEATS) L(`- ${c}`);
  L();
  return `${lines.join("\n")}\n`;
}
